CREATE TABLE IF NOT EXISTS Roles (
  Id INT AUTO_INCREMENT PRIMARY KEY,
  Name VARCHAR(100) NOT NULL UNIQUE,
  CreatedAt DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP
) ENGINE=InnoDB;

CREATE TABLE IF NOT EXISTS Users (
  Id INT AUTO_INCREMENT PRIMARY KEY,
  FullName VARCHAR(200) NOT NULL,
  Email VARCHAR(200) NOT NULL UNIQUE,
  PasswordHash VARCHAR(255) NOT NULL,
  RoleId INT NOT NULL,
  IsActive TINYINT(1) NOT NULL DEFAULT 1,
  CreatedAt DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP,
  UpdatedAt DATETIME NULL,
  CONSTRAINT FK_Users_Roles FOREIGN KEY (RoleId) REFERENCES Roles(Id)
) ENGINE=InnoDB;

CREATE TABLE IF NOT EXISTS Organizations (
  Id INT AUTO_INCREMENT PRIMARY KEY,
  Name VARCHAR(255) NOT NULL UNIQUE,
  Category VARCHAR(150) NULL,
  CreatedAt DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP,
  UpdatedAt DATETIME NULL
) ENGINE=InnoDB;

CREATE TABLE IF NOT EXISTS Countries (
  Id INT AUTO_INCREMENT PRIMARY KEY,
  Name VARCHAR(150) NOT NULL UNIQUE,
  IsoCode VARCHAR(10) NULL,
  CreatedAt DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP
) ENGINE=InnoDB;

CREATE TABLE IF NOT EXISTS Sources (
  Id INT AUTO_INCREMENT PRIMARY KEY,
  Name VARCHAR(255) NOT NULL,
  OrganizationId INT NULL,
  CountryId INT NULL,
  ScraperType VARCHAR(150) NULL,
  SearchType VARCHAR(50) NULL,
  FrequencyMinutes INT NOT NULL DEFAULT 1440,
  Url VARCHAR(1000) NOT NULL,
  Email VARCHAR(255) NULL,
  Category VARCHAR(150) NULL,
  IsActive TINYINT(1) NOT NULL DEFAULT 1,
  CreatedAt DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP,
  UpdatedAt DATETIME NULL,
  CONSTRAINT FK_Sources_Organizations FOREIGN KEY (OrganizationId) REFERENCES Organizations(Id),
  CONSTRAINT FK_Sources_Countries FOREIGN KEY (CountryId) REFERENCES Countries(Id)
) ENGINE=InnoDB;

CREATE TABLE IF NOT EXISTS Keywords (
  Id INT AUTO_INCREMENT PRIMARY KEY,
  Keyword VARCHAR(255) NOT NULL UNIQUE,
  GroupName VARCHAR(100) NOT NULL,
  Points INT NOT NULL DEFAULT 0,
  IsActive TINYINT(1) NOT NULL DEFAULT 1,
  CreatedAt DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP,
  UpdatedAt DATETIME NULL
) ENGINE=InnoDB;

CREATE TABLE IF NOT EXISTS Opportunities (
  Id BIGINT AUTO_INCREMENT PRIMARY KEY,
  SourceId INT NULL,
  OrganizationId INT NULL,
  CountryId INT NULL,
  Title VARCHAR(1000) NOT NULL,
  Description TEXT NULL,
  Url VARCHAR(1000) NOT NULL,
  CombinedHash VARCHAR(64) NOT NULL,
  CategoryName VARCHAR(150) NULL,
  PublishedAt DATETIME NULL,
  Deadline DATETIME NULL,
  IsApplied TINYINT(1) NOT NULL DEFAULT 0,
  DetectedAt DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP,
  RelevanceScore INT NOT NULL DEFAULT 0,
  RelevanceLevel VARCHAR(50) NOT NULL DEFAULT 'Baja',
  IsAlertSent TINYINT(1) NOT NULL DEFAULT 0,
  UNIQUE KEY UQ_Opportunities_CombinedHash (CombinedHash),
  CONSTRAINT FK_Opportunities_Sources FOREIGN KEY (SourceId) REFERENCES Sources(Id),
  CONSTRAINT FK_Opportunities_Organizations FOREIGN KEY (OrganizationId) REFERENCES Organizations(Id),
  CONSTRAINT FK_Opportunities_Countries FOREIGN KEY (CountryId) REFERENCES Countries(Id)
) ENGINE=InnoDB;

CREATE TABLE IF NOT EXISTS OpportunityMatches (
  Id BIGINT AUTO_INCREMENT PRIMARY KEY,
  OpportunityId BIGINT NOT NULL,
  KeywordId INT NULL,
  KeywordText VARCHAR(255) NOT NULL,
  GroupName VARCHAR(100) NOT NULL,
  Points INT NOT NULL,
  CreatedAt DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP,
  CONSTRAINT FK_OpportunityMatches_Opportunities FOREIGN KEY (OpportunityId) REFERENCES Opportunities(Id),
  CONSTRAINT FK_OpportunityMatches_Keywords FOREIGN KEY (KeywordId) REFERENCES Keywords(Id)
) ENGINE=InnoDB;

CREATE TABLE IF NOT EXISTS ScraperLogs (
  Id BIGINT AUTO_INCREMENT PRIMARY KEY,
  SourceId INT NULL,
  ScraperName VARCHAR(150) NOT NULL,
  Status VARCHAR(50) NOT NULL,
  Message TEXT NULL,
  RecordsFound INT NOT NULL DEFAULT 0,
  CreatedAt DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP,
  CONSTRAINT FK_ScraperLogs_Sources FOREIGN KEY (SourceId) REFERENCES Sources(Id)
) ENGINE=InnoDB;

CREATE TABLE IF NOT EXISTS ImportLogs (
  Id BIGINT AUTO_INCREMENT PRIMARY KEY,
  FileName VARCHAR(500) NOT NULL,
  SheetName VARCHAR(255) NULL,
  Status VARCHAR(50) NOT NULL,
  TotalRows INT NOT NULL DEFAULT 0,
  ImportedRows INT NOT NULL DEFAULT 0,
  ErrorMessage TEXT NULL,
  CreatedAt DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP
) ENGINE=InnoDB;

CREATE TABLE IF NOT EXISTS ScraperState (
  SourceId INT PRIMARY KEY,
  LastScanDate DATETIME NULL,
  LastPublicationDate DATETIME NULL,
  LastHash VARCHAR(64) NULL,
  LastUrl VARCHAR(1000) NULL,
  LastTitle VARCHAR(1000) NULL,
  Status VARCHAR(50) NULL,
  UpdatedAt DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP,
  CONSTRAINT FK_ScraperState_Sources FOREIGN KEY (SourceId) REFERENCES Sources(Id)
) ENGINE=InnoDB;

CREATE TABLE IF NOT EXISTS SystemSettings (
  Id INT AUTO_INCREMENT PRIMARY KEY,
  `Key` VARCHAR(200) NOT NULL UNIQUE,
  `Value` TEXT NULL,
  UpdatedAt DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP
) ENGINE=InnoDB;

CREATE TABLE IF NOT EXISTS Alerts (
  Id BIGINT AUTO_INCREMENT PRIMARY KEY,
  OpportunityId BIGINT NOT NULL,
  Channel VARCHAR(50) NOT NULL,
  Recipient VARCHAR(255) NULL,
  Status VARCHAR(50) NOT NULL DEFAULT 'Sent',
  SentAt DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP,
  Details TEXT NULL,
  CONSTRAINT FK_Alerts_Opportunities FOREIGN KEY (OpportunityId) REFERENCES Opportunities(Id)
) ENGINE=InnoDB;

CREATE OR REPLACE VIEW vw_OpportunityMonitor AS
SELECT 
  o.Id,
  o.Title,
  o.Description,
  o.Url,
  o.PublishedAt,
  o.Deadline,
  o.IsApplied,
  o.DetectedAt,
  o.RelevanceScore,
  o.RelevanceLevel,
  s.Name AS SourceName,
  org.Name AS OrganizationName,
  c.Name AS CountryName,
  o.CategoryName
FROM Opportunities o
LEFT JOIN Sources s ON s.Id = o.SourceId
LEFT JOIN Organizations org ON org.Id = o.OrganizationId
LEFT JOIN Countries c ON c.Id = o.CountryId;
