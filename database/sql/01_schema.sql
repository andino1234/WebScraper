CREATE TABLE Roles (
  Id INT IDENTITY(1,1) PRIMARY KEY,
  Name NVARCHAR(100) NOT NULL UNIQUE,
  CreatedAt DATETIME2 NOT NULL DEFAULT GETDATE()
);

CREATE TABLE Users (
  Id INT IDENTITY(1,1) PRIMARY KEY,
  FullName NVARCHAR(200) NOT NULL,
  Email NVARCHAR(200) NOT NULL UNIQUE,
  PasswordHash NVARCHAR(255) NOT NULL,
  RoleId INT NOT NULL,
  IsActive BIT NOT NULL DEFAULT 1,
  CreatedAt DATETIME2 NOT NULL DEFAULT GETDATE(),
  UpdatedAt DATETIME2 NULL,
  CONSTRAINT FK_Users_Roles FOREIGN KEY (RoleId) REFERENCES Roles(Id)
);

CREATE TABLE Organizations (
  Id INT IDENTITY(1,1) PRIMARY KEY,
  Name NVARCHAR(255) NOT NULL UNIQUE,
  Category NVARCHAR(150) NULL,
  CreatedAt DATETIME2 NOT NULL DEFAULT GETDATE(),
  UpdatedAt DATETIME2 NULL
);

CREATE TABLE Countries (
  Id INT IDENTITY(1,1) PRIMARY KEY,
  Name NVARCHAR(150) NOT NULL UNIQUE,
  IsoCode NVARCHAR(10) NULL,
  CreatedAt DATETIME2 NOT NULL DEFAULT GETDATE()
);

CREATE TABLE Sources (
  Id INT IDENTITY(1,1) PRIMARY KEY,
  Name NVARCHAR(255) NOT NULL,
  OrganizationId INT NULL,
  CountryId INT NULL,
  Url NVARCHAR(1000) NOT NULL,
  Email NVARCHAR(255) NULL,
  Category NVARCHAR(150) NULL,
  ScraperType NVARCHAR(150) NULL,
  SearchType NVARCHAR(50) NULL,
  FrequencyMinutes INT NOT NULL DEFAULT 1440,
  IsActive BIT NOT NULL DEFAULT 1,
  CreatedAt DATETIME2 NOT NULL DEFAULT GETDATE(),
  UpdatedAt DATETIME2 NULL,
  CONSTRAINT FK_Sources_Organizations FOREIGN KEY (OrganizationId) REFERENCES Organizations(Id),
  CONSTRAINT FK_Sources_Countries FOREIGN KEY (CountryId) REFERENCES Countries(Id)
);

CREATE TABLE KeywordGroups (
  Id INT IDENTITY(1,1) PRIMARY KEY,
  Name NVARCHAR(100) NOT NULL UNIQUE,
  BasePoints INT NOT NULL DEFAULT 0,
  CreatedAt DATETIME2 NOT NULL DEFAULT GETDATE()
);

CREATE TABLE Keywords (
  Id INT IDENTITY(1,1) PRIMARY KEY,
  Keyword NVARCHAR(255) NOT NULL UNIQUE,
  GroupName NVARCHAR(100) NOT NULL,
  Points INT NOT NULL DEFAULT 0,
  IsActive BIT NOT NULL DEFAULT 1,
  CreatedAt DATETIME2 NOT NULL DEFAULT GETDATE(),
  UpdatedAt DATETIME2 NULL
);

CREATE TABLE Opportunities (
  Id BIGINT IDENTITY(1,1) PRIMARY KEY,
  SourceId INT NULL,
  OrganizationId INT NULL,
  CountryId INT NULL,
  Title NVARCHAR(1000) NOT NULL,
  Description NVARCHAR(MAX) NULL,
  Url NVARCHAR(1000) NOT NULL,
  UrlHash NVARCHAR(64) NOT NULL,
  TitleHash NVARCHAR(64) NULL,
  CombinedHash NVARCHAR(64) NOT NULL,
  CategoryName NVARCHAR(150) NULL,
  PublishedAt DATETIME2 NULL,
  DetectedAt DATETIME2 NOT NULL DEFAULT GETDATE(),
  RelevanceScore INT NOT NULL DEFAULT 0,
  RelevanceLevel NVARCHAR(50) NOT NULL DEFAULT 'Baja',
  IsAlertSent BIT NOT NULL DEFAULT 0,
  CONSTRAINT UQ_Opportunities_CombinedHash UNIQUE (CombinedHash),
  CONSTRAINT FK_Opportunities_Sources FOREIGN KEY (SourceId) REFERENCES Sources(Id),
  CONSTRAINT FK_Opportunities_Organizations FOREIGN KEY (OrganizationId) REFERENCES Organizations(Id),
  CONSTRAINT FK_Opportunities_Countries FOREIGN KEY (CountryId) REFERENCES Countries(Id)
);

CREATE TABLE OpportunityMatches (
  Id BIGINT IDENTITY(1,1) PRIMARY KEY,
  OpportunityId BIGINT NOT NULL,
  KeywordId INT NULL,
  KeywordText NVARCHAR(255) NOT NULL,
  GroupName NVARCHAR(100) NOT NULL,
  Points INT NOT NULL,
  CreatedAt DATETIME2 NOT NULL DEFAULT GETDATE(),
  CONSTRAINT FK_OpportunityMatches_Opportunities FOREIGN KEY (OpportunityId) REFERENCES Opportunities(Id),
  CONSTRAINT FK_OpportunityMatches_Keywords FOREIGN KEY (KeywordId) REFERENCES Keywords(Id)
);

CREATE TABLE Alerts (
  Id BIGINT IDENTITY(1,1) PRIMARY KEY,
  OpportunityId BIGINT NOT NULL,
  Channel NVARCHAR(50) NOT NULL,
  Recipient NVARCHAR(255) NULL,
  Status NVARCHAR(50) NOT NULL DEFAULT 'Sent',
  SentAt DATETIME2 NOT NULL DEFAULT GETDATE(),
  Details NVARCHAR(MAX) NULL,
  CONSTRAINT FK_Alerts_Opportunities FOREIGN KEY (OpportunityId) REFERENCES Opportunities(Id)
);

CREATE TABLE ScraperLogs (
  Id BIGINT IDENTITY(1,1) PRIMARY KEY,
  SourceId INT NULL,
  ScraperName NVARCHAR(150) NOT NULL,
  Status NVARCHAR(50) NOT NULL,
  Message NVARCHAR(MAX) NULL,
  RecordsFound INT NOT NULL DEFAULT 0,
  CreatedAt DATETIME2 NOT NULL DEFAULT GETDATE(),
  CONSTRAINT FK_ScraperLogs_Sources FOREIGN KEY (SourceId) REFERENCES Sources(Id)
);

CREATE TABLE ImportLogs (
  Id BIGINT IDENTITY(1,1) PRIMARY KEY,
  FileName NVARCHAR(500) NOT NULL,
  SheetName NVARCHAR(255) NULL,
  Status NVARCHAR(50) NOT NULL,
  TotalRows INT NOT NULL DEFAULT 0,
  ImportedRows INT NOT NULL DEFAULT 0,
  ErrorMessage NVARCHAR(MAX) NULL,
  CreatedAt DATETIME2 NOT NULL DEFAULT GETDATE()
);

CREATE TABLE ScraperState (
  SourceId INT PRIMARY KEY,
  LastScanDate DATETIME2 NULL,
  LastPublicationDate DATETIME2 NULL,
  LastHash NVARCHAR(64) NULL,
  LastUrl NVARCHAR(1000) NULL,
  LastTitle NVARCHAR(1000) NULL,
  Status NVARCHAR(50) NULL,
  UpdatedAt DATETIME2 NOT NULL DEFAULT GETDATE(),
  CONSTRAINT FK_ScraperState_Sources FOREIGN KEY (SourceId) REFERENCES Sources(Id)
);

CREATE TABLE SystemSettings (
  Id INT IDENTITY(1,1) PRIMARY KEY,
  [Key] NVARCHAR(200) NOT NULL UNIQUE,
  [Value] NVARCHAR(MAX) NULL,
  UpdatedAt DATETIME2 NOT NULL DEFAULT GETDATE()
);

CREATE INDEX IX_Opportunities_DetectedAt ON Opportunities(DetectedAt DESC);
CREATE INDEX IX_Opportunities_RelevanceLevel ON Opportunities(RelevanceLevel);
CREATE INDEX IX_Sources_IsActive ON Sources(IsActive);
CREATE INDEX IX_Keywords_GroupName ON Keywords(GroupName);
